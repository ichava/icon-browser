#!/usr/bin/env node
// Regenerates the brand bridge block in src/styles/theme.css (see the comment above it).
//
//   node scripts/brand-bridge.mjs          rewrite the block between the markers
//   node scripts/brand-bridge.mjs --check  exit 1 if the block is out of date
//
// The block re-declares, on the component root, every `:root` token whose value depends
// on `--color-brand-*`, with the same expression `:root` uses. A custom property's var()
// references resolve where it is DECLARED, so a token declared only at `:root` has the
// shipped purple substituted there, and the ramp the component root writes never reaches
// it. `src/styles/brandBridge.test.ts` runs the same derivation, so a resync of
// uui-theme.css that adds a brand token fails `npm test` until this is re-run.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { stripCssComments } from '@ichava/js-ui-kernel/build';
import { fileURLToPath } from 'node:url';

export const BEGIN = '/* brand-bridge:begin (generated by scripts/brand-bridge.mjs; do not edit by hand) */';
export const END = '/* brand-bridge:end */';

/** Variables the component root writes inline; inline wins, so re-declaring them is noise. */
export const INLINE = new Set(['--accent', '--accent-text', '--accent-soft', '--ring', '--radius']);

const WORD = /[\w-]/;
const SPACE = /\s/;

/**
 * `name: value` declarations in a CSS fragment, comments stripped: exactly the matches of
 * `/(--[\w-]+)\s*:\s*([^;{}]+);/g`, with the value trimmed, found in one pass.
 *
 * That regex is polynomial: `\s*` and `[^;{}]+` both take spaces, and `[\w-]+` retries
 * from every dash, so a long unterminated value or a run of dashes took seconds. Here
 * each position is visited a fixed number of times. Comments go through the kernel's
 * linear `stripCssComments` for the same reason.
 */
export function declarations(css) {
  const text = stripCssComments(css);
  const n = text.length;
  // wordEnd[i]: the first index >= i outside [\w-]; spaceEnd[i]: outside \s;
  // stop[i]: the first index >= i holding one of ; { } (n when none).
  const wordEnd = new Int32Array(n + 1);
  const spaceEnd = new Int32Array(n + 1);
  const stop = new Int32Array(n + 1);
  wordEnd[n] = spaceEnd[n] = stop[n] = n;
  for (let i = n - 1; i >= 0; i--) {
    const c = text[i];
    wordEnd[i] = WORD.test(c) ? wordEnd[i + 1] : i;
    spaceEnd[i] = SPACE.test(c) ? spaceEnd[i + 1] : i;
    stop[i] = c === ';' || c === '{' || c === '}' ? i : stop[i + 1];
  }
  const out = [];
  for (let p = 0; p + 1 < n; ) {
    if (text[p] === '-' && text[p + 1] === '-') {
      const nameEnd = wordEnd[p + 2];
      const colon = spaceEnd[nameEnd];
      if (nameEnd > p + 2 && text[colon] === ':') {
        const end = stop[colon + 1];
        if (end < n && text[end] === ';' && end > colon + 1) {
          out.push([text.slice(p, nameEnd), text.slice(colon + 1, end).trim()]);
          p = end + 1;
          continue;
        }
      }
    }
    p += 1;
  }
  return out;
}

/** The `:root`-level declarations: Untitled UI's `@theme` block plus theme.css's `:root` block. */
export function rootDeclarations(uuiCss, themeCss) {
  const theme = uuiCss.slice(uuiCss.indexOf('@theme'), uuiCss.indexOf('@layer base'));
  const open = themeCss.indexOf(':root {');
  const app = open < 0 ? '' : themeCss.slice(open, themeCss.indexOf('\n  }\n', open));
  return [...declarations(theme), ...declarations(app)];
}

/** Every declaration that depends, directly or transitively, on `--color-brand-<n>`. */
export function brandDependents(decls) {
  const map = new Map(decls);
  const dep = new Set([...map.keys()].filter((k) => /^--color-brand-\d+$/.test(k)));
  for (let changed = true; changed; ) {
    changed = false;
    for (const [k, v] of map) {
      if (dep.has(k)) continue;
      if ([...v.matchAll(/var\(\s*(--[\w-]+)/g)].some((m) => dep.has(m[1]))) {
        dep.add(k);
        changed = true;
      }
    }
  }
  return [...map].filter(([k]) => dep.has(k) && !/^--color-brand-\d+$/.test(k) && !INLINE.has(k));
}

export function renderBlock(entries) {
  const body = entries.map(([k, v]) => `    ${k}: ${v};`).join('\n');
  return `${BEGIN}\n@layer base {\n  :where([data-ichava-theme]) {\n${body}\n  }\n}\n${END}`;
}

export function currentBlock(themeCss) {
  const a = themeCss.indexOf(BEGIN);
  const b = themeCss.indexOf(END);
  return a < 0 || b < 0 ? null : themeCss.slice(a, b + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const themePath = join(root, 'src/styles/theme.css');
  const uui = readFileSync(join(root, 'src/styles/uui-theme.css'), 'utf8');
  const themeCss = readFileSync(themePath, 'utf8');
  const entries = brandDependents(rootDeclarations(uui, themeCss));
  if (entries.length < 50) {
    console.error(`::error::only ${entries.length} brand-dependent tokens found; the parse is probably broken`);
    process.exit(1);
  }
  const want = renderBlock(entries);
  const have = currentBlock(themeCss);
  if (have === null) {
    console.error('::error::brand-bridge markers not found in src/styles/theme.css');
    process.exit(1);
  }
  if (process.argv.includes('--check')) {
    if (have !== want) {
      console.error('::error::the brand bridge in theme.css is stale; run node scripts/brand-bridge.mjs');
      process.exit(1);
    }
    console.log(`brand-bridge: ok -- ${entries.length} tokens`);
  } else {
    writeFileSync(themePath, themeCss.replace(have, want));
    console.log(`brand-bridge: wrote ${entries.length} tokens`);
  }
}
